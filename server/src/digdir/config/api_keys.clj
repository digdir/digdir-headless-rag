(defn- pull-access-policy-entity
  [db policy-id]
  (when-let [base-entity (d/pull db access-policy-base-pull-pattern [:access-policy/id policy-id])]
    (normalize-access-policy-entity
     (assoc base-entity
            :access-policy/dataset-scopes (query-access-policy-dataset-scopes db policy-id)
            :access-policy/agent-refs (query-access-policy-agent-refs db policy-id)
            :access-policy/allowed-config-keys (query-access-policy-allowed-config-keys db policy-id)))))

(defn- normalize-access-policy-entity
  [policy-entity]
  (let [dataset-scopes (mapv (fn [dataset-scope]
                               {:tenant (:api-key.dataset-scope/tenant dataset-scope)
                                :dataset-config-key (:api-key.dataset-scope/dataset-config-key dataset-scope)})
                             (:access-policy/dataset-scopes policy-entity))
        tenants (if (seq (:access-policy/tenants policy-entity))
                  (vec (:access-policy/tenants policy-entity))
                  (dataset-scopes->tenants dataset-scopes))
        agent-refs (->> (:access-policy/agent-refs policy-entity)
                        (mapv :api-key.agent-ref/agent-id))
        allowed-config-keys (->> (:access-policy/allowed-config-keys policy-entity)
                                 (mapv normalize-pulled-allowed-config-key)
                                 vec)]
    (-> policy-entity
        (assoc :access-policy/dataset-scopes dataset-scopes
               :access-policy/agent-refs agent-refs
               :access-policy/allowed-config-keys allowed-config-keys
               :access-policy/tenants tenants
               :access-policy/clients (vec (:access-policy/clients policy-entity))
               :access-policy/skill-graphs (vec (:access-policy/skill-graphs policy-entity))
               :access-policy/scopes (normalize-scopes (:access-policy/scopes policy-entity))))))

