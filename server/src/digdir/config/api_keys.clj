(defn- resolve-allowed-config-key-node!
  [conn {:keys [root tenant node-id tenant-config-key]}]
  (let [config-db-value (or (some-> (config-db/get-conn) deref)
                            @conn)
        node (cond
               node-id (config-db/get-config-node config-db-value node-id)
               tenant-config-key (config-db/get-config-node-by-tenant-config-key config-db-value tenant root tenant-config-key)
               :else nil)]
    (when-not node
      (throw (ex-info "Allowed config key references unknown config node"
                      {:root root
                       :tenant tenant
                       :node-id node-id
                       :tenant-config-key tenant-config-key})))
    (when-not (:config.node/enabled? node)
      (throw (ex-info "Allowed config key references disabled config node"
                      {:root root
                       :tenant tenant
                       :node-id (:config.node/id node)
                       :tenant-config-key (:config.node/tenant-config-key node)})))
    (when-not (= root (:config.node/root node))
      (throw (ex-info "Allowed config key root mismatch"
                      {:root root
                       :tenant tenant
                       :node-id (:config.node/id node)
                       :node-root (:config.node/root node)})))
    (when-not (= tenant (:config.node/tenant node))
      (throw (ex-info "Allowed config key tenant mismatch"
                      {:root root
                       :tenant tenant
                       :node-id (:config.node/id node)
                       :node-tenant (:config.node/tenant node)})))
    (when (str/blank? (:config.node/tenant-config-key node))
      (throw (ex-info "Allowed config key node must have a stable tenant-config-key"
                      {:root root
                       :tenant tenant
                       :node-id (:config.node/id node)})))
    node))

(defn- resolvable-main-db-config-node-ref
  [db node-id]
  (when-not (str/blank? node-id)
    (try
      (when (config-db/get-config-node db node-id)
        [:config.node/id node-id])
      (catch Exception _
        nil))))

(defn- build-allowed-config-key-tx-data
  [conn allowed-config-keys]
  (mapv (fn [{:keys [root tenant node-id tenant-config-key]}]
          (let [main-db @conn
                node (resolve-allowed-config-key-node! conn {:root root
                                                             :tenant tenant
                                                             :node-id node-id
                                                             :tenant-config-key tenant-config-key})
                allowed-config-key-id (str "api-key-allowed-config-key-" (nano-id))]
            (cond-> {:api-key.allowed-config-key/id allowed-config-key-id
                     :api-key.allowed-config-key/root root
                     :api-key.allowed-config-key/tenant tenant
                     :api-key.allowed-config-key/node-id (:config.node/id node)
                     :api-key.allowed-config-key/tenant-config-key (:config.node/tenant-config-key node)
                     :api-key.allowed-config-key/created-at (.getTime (t/inst (t/now)))}
              (resolvable-main-db-config-node-ref main-db (:config.node/id node))
              (assoc :api-key.allowed-config-key/node
                     (resolvable-main-db-config-node-ref main-db (:config.node/id node))))))
        allowed-config-keys))

(defn- resolve-eid-by-attr
  [db attr value]
  (d/q '[:find ?e .
         :in $ ?attr ?value
         :where [?e ?attr ?value]]
       db
       attr
       value))

(defn- resolve-eids-by-attr
  [db attr entities]
  (mapv (fn [entity]
          (let [value (get entity attr)
                eid (resolve-eid-by-attr db attr value)]
            (when-not eid
              (throw (ex-info "Failed to resolve API key child entity"
                              {:attr attr
                               :value value})))
            eid))
        entities))

(defn- build-parent-ref-assertions
  [api-key-eid attr ref-eids]
  (mapv (fn [ref-eid]
          [:db/add api-key-eid attr ref-eid])
        ref-eids))

(defn- transact-ref-assertions!
  [conn ref-assertions]
  (when (seq ref-assertions)
    (d/transact conn {:tx-data (vec ref-assertions)})))

