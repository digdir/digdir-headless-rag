(defn- normalize-dataset-scope
  [dataset-scope]
  (let [tenant (or (:tenant dataset-scope) (get dataset-scope "tenant"))
        dataset-config-key (or (:dataset-config-key dataset-scope)
                               (get dataset-scope "dataset-config-key")
                               (get dataset-scope "dataset_config_key")
                               (:tenant-config-key dataset-scope)
                               (get dataset-scope "tenant-config-key")
                               (get dataset-scope "tenant_config_key")
                               (:config-key dataset-scope)
                               (get dataset-scope "config-key")
                               (get dataset-scope "config_key"))]
    (when (and (string? tenant)
               (string? dataset-config-key)
               (not (str/blank? tenant))
               (not (str/blank? dataset-config-key)))
      {:tenant tenant
       :dataset-config-key dataset-config-key})))

(defn- distinct-by*
  [f coll]
  (let [[_ result]
        (reduce (fn [[seen acc] item]
                  (let [k (f item)]
                    (if (contains? seen k)
                      [seen acc]
                      [(conj seen k) (conj acc item)])))
                [#{} []]
                coll)]
    result))

(defn- normalize-dataset-scopes
  [{:keys [dataset-scopes]}]
  (->> (map normalize-dataset-scope (or dataset-scopes []))
       (remove nil?)
       (distinct-by* (juxt :tenant :dataset-config-key))
       vec))

(defn- normalize-scope
  [scope]
  (cond
    (keyword? scope) scope
    (symbol? scope) (keyword (name scope))
    (string? scope) (let [s (str/trim scope)]
                      (when-not (str/blank? s)
                        (keyword (str/replace s #"^:+"
                                              ""))))
    :else nil))

(defn- normalize-scopes
  [scopes]
  (->> (or scopes [])
       (map normalize-scope)
       (filter valid-scopes)
       distinct
       vec))

(defn- normalize-agent-ref
  [agent-ref]
  (let [agent-id (cond
                   (string? agent-ref) agent-ref
                   (keyword? agent-ref) (name agent-ref)
                   (map? agent-ref) (or (:agent-id agent-ref)
                                        (:agent/id agent-ref)
                                        (get agent-ref "agent-id")
                                        (get agent-ref "agent/id"))
                   :else nil)]
    (when (and (string? agent-id) (not (str/blank? agent-id)))
      agent-id)))

(defn- normalize-agent-refs
  [agent-refs]
  (->> (or agent-refs [])
       (map normalize-agent-ref)
       (remove nil?)
       distinct
       vec))

(defn- normalize-config-key-string
  [v]
  (cond
    (nil? v) nil
    (string? v) (let [s (str/trim v)]
                  (when-not (str/blank? s)
                    s))
    (keyword? v) (let [s (name v)]
                   (when-not (str/blank? s)
                     s))
    (symbol? v) (let [s (str v)]
                  (when-not (str/blank? s)
                    s))
    :else (let [s (str v)]
            (when-not (str/blank? s)
              s))))

(defn- normalize-allowed-config-key
  [allowed-config-key]
  (let [root (some-> (or (:root allowed-config-key)
                         (:api-key.allowed-config-key/root allowed-config-key)
                         (get allowed-config-key "root")
                         (get allowed-config-key "api-key.allowed-config-key/root"))
                     keyword)
        tenant (or (:tenant allowed-config-key)
                   (:api-key.allowed-config-key/tenant allowed-config-key)
                   (get allowed-config-key "tenant")
                   (get allowed-config-key "api-key.allowed-config-key/tenant"))
        node-id (normalize-config-key-string
                 (or (:node-id allowed-config-key)
                     (:api-key.allowed-config-key/node-id allowed-config-key)
                     (get allowed-config-key "node-id")
                     (get allowed-config-key "api-key.allowed-config-key/node-id")))
        tenant-config-key (or (case root
                                :platform (or (:platform-config-key allowed-config-key)
                                              (get allowed-config-key "platform-config-key")
                                              (get allowed-config-key "platform_config_key"))
                                :runtime (or (:runtime-config-key allowed-config-key)
                                             (get allowed-config-key "runtime-config-key")
                                             (get allowed-config-key "runtime_config_key"))
                                :dataset (or (:dataset-config-key allowed-config-key)
                                             (get allowed-config-key "dataset-config-key")
                                             (get allowed-config-key "dataset_config_key"))
                                nil)
                              (:tenant-config-key allowed-config-key)
                              (:api-key.allowed-config-key/tenant-config-key allowed-config-key)
                              (get allowed-config-key "tenant-config-key")
                              (get allowed-config-key "tenant_config_key")
                              (:config-key allowed-config-key)
                              (get allowed-config-key "config-key")
                              (get allowed-config-key "config_key")
                              (get allowed-config-key "api-key.allowed-config-key/tenant-config-key"))]
    (when-not (contains? valid-config-roots root)
      (throw (ex-info "Invalid allowed config key root"
                      {:root root
                       :valid-roots (sort valid-config-roots)})))
    (when-not (and (string? (normalize-config-key-string tenant))
                   (not (str/blank? (normalize-config-key-string tenant))))
      (throw (ex-info "Allowed config key tenant is required"
                      {:tenant tenant})))
    (when-not (or (and node-id (not (str/blank? node-id)))
                  (and (normalize-config-key-string tenant-config-key)
                       (not (str/blank? (normalize-config-key-string tenant-config-key)))))
      (throw (ex-info "Allowed config key requires node-id or tenant-config-key"
                      {:root root
                       :tenant tenant})))
    {:root root
     :tenant (normalize-config-key-string tenant)
     :node-id node-id
     :tenant-config-key (normalize-config-key-string tenant-config-key)}))

(defn- normalize-allowed-config-keys
  [allowed-config-keys]
  (->> (or allowed-config-keys [])
       (map normalize-allowed-config-key)
       (distinct-by* (juxt :root :tenant :node-id :tenant-config-key))
       vec))

(defn- normalize-pulled-allowed-config-key
  [allowed-config-key]
  (let [{:keys [root tenant node-id tenant-config-key]}
        (normalize-allowed-config-key {:root (:api-key.allowed-config-key/root allowed-config-key)
                                       :tenant (:api-key.allowed-config-key/tenant allowed-config-key)
                                       :node-id (:api-key.allowed-config-key/node-id allowed-config-key)
                                       :tenant-config-key (:api-key.allowed-config-key/tenant-config-key allowed-config-key)})]
    (cond-> {:api-key.allowed-config-key/id (:api-key.allowed-config-key/id allowed-config-key)
             :api-key.allowed-config-key/root root
             :api-key.allowed-config-key/tenant tenant}
      node-id
      (assoc :api-key.allowed-config-key/node-id node-id)

      tenant-config-key
      (assoc :api-key.allowed-config-key/tenant-config-key tenant-config-key)

      (:api-key.allowed-config-key/created-at allowed-config-key)
      (assoc :api-key.allowed-config-key/created-at (:api-key.allowed-config-key/created-at allowed-config-key)))))

