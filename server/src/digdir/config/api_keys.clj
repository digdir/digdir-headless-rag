(defn- query-access-policy-dataset-scopes
  [db policy-id]
  (let [ref-eids (d/q '[:find [?ref ...]
                        :in $ ?policy-id
                        :where
                        [?p :access-policy/id ?policy-id]
                        [?p :access-policy/dataset-scopes ?ref]]
                      db policy-id)]
    (->> ref-eids
         (filter some?)
         (keep (fn [ref-eid]
                 (when (or (not (coll? ref-eid))
                           (and (vector? ref-eid) (= 2 (count ref-eid))))
                   (try
                     (d/pull db '[:api-key.dataset-scope/id
                                  :api-key.dataset-scope/tenant
                                  :api-key.dataset-scope/dataset-config-key]
                             ref-eid)
                     (catch Exception _
                       nil)))))
         (remove nil?)
         vec)))

(defn- query-access-policy-agent-refs
  [db policy-id]
  (let [rows (d/q '[:find ?ref-id ?agent-id
                    :in $ ?policy-id
                    :where
                    [?p :access-policy/id ?policy-id]
                    [?p :access-policy/agent-refs ?ref]
                    [?ref :api-key.agent-ref/id ?ref-id]
                    [?ref :api-key.agent-ref/agent-id ?agent-id]]
                  db policy-id)]
    (if (coll? rows)
      (mapv (fn [[ref-id agent-id]]
              {:api-key.agent-ref/id ref-id
               :api-key.agent-ref/agent-id agent-id})
            rows)
      [])))

