;; API Key Generation and Management
;;
;; This namespace provides functions for generating, storing, validating,
;; and revoking API keys used for authentication to the RAG API endpoint.
;;
;; Features:
;; - API keys are 32-byte random hex strings (256 bits of entropy)
;; - Only SHA-256 digests and non-secret display metadata are stored
;; - Legacy plaintext rows are upgraded after a successful authentication
;; - Keys can be revoked without deletion (maintains audit trail)
;; - Last-used timestamp is tracked for monitoring
;; - All operations are logged to the audit log

(defn generate-api-key
  "Generate a secure random API key (32-byte hex string).
  Format: 'rag_' prefix followed by 64 hex characters.
  Example: rag_a1b2c3d4e5f6...

  The 'rag_' prefix makes it easy to identify RAG API keys in logs/code."
  []
  (let [random-bytes (byte-array 32)]
    (doto (java.security.SecureRandom.)
      (.nextBytes random-bytes))
    (str "rag_" (apply str (map #(format "%02x" %) random-bytes)))))

(defn api-key-digest
  "Return the lowercase SHA-256 digest used to look up an API key.

  API keys contain 256 bits generated by SecureRandom, so an offline preimage
  attack remains infeasible without a server-side pepper. Using an unkeyed
  digest also avoids introducing a second bootstrap secret whose loss would
  invalidate every deployed key. The plaintext is never used as a database
  identity for newly-created or imported keys."
  [api-key]
  (when api-key
    (let [digest (.digest (java.security.MessageDigest/getInstance "SHA-256")
                          (.getBytes ^String api-key java.nio.charset.StandardCharsets/UTF_8))]
      (apply str (map #(format "%02x" (bit-and (int %) 0xff)) digest)))))

(defn api-key-display-metadata
  "Return non-secret fields suitable for key lists and audit displays."
  [api-key]
  (when api-key
    (let [length (count api-key)]
      {:api-key/prefix (subs api-key 0 (min 8 length))
       :api-key/last-four (subs api-key (max 0 (- length 4)))})))

(def valid-scopes
  "Set of valid API key scopes"
  #{:query :ingest :admin})

